.ORIG x3000

LD R1, ARRAY_SIZE
LEA R6, ARRAY


FILL_ARRAY_LOOP
LEA R0, PROMPT
PUTS
GETC
OUT

LD R2, ASCII
NOT R2, R2
ADD R2, R2, #1
ADD R0, R0, R2

STR R0, R6, #0

ADD R6, R6, #1
ADD R1, R1, #-1
BRp FILL_ARRAY_LOOP

HALT

ARRAY_SIZE .FILL #10
ARRAY .BLKW #10
ASCII .FILL X0030
PROMPT .STRINGZ "ENTER A NUMBER: "

.END