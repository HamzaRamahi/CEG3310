.ORIG x3000 

LOOP 

LEA R0, PROMPT1
PUTS

JSR GETNUM
ST R0, NUM1

LEA R0, PROMPT2
PUTS

JSR GETOP
ST R0, OP

LEA R0, PROMPT3
PUTS

JSR GETNUM
ST R0, NUM2

LD R0, NUM1
LD R1, NUM2
LD R2, OP

JSR CALC
JSR DISPLAY
BRNZP LOOP

HALT

GETNUM 
ST R7, SAVER7

AND R1, R1, #0

GNLOOP 
GETC
ADD R2,R0, #-10
BRz GNDONE

OUT
LD R3, NEG48

ADD R0, R0, R3
ADD R2, R1, R1
ADD R1,R2,R2
ADD R1,R1,R1
ADD R1,R1,R2
ADD R1, R1, R0
BRnzp GNLOOP
GNDONE 
ADD R0,R1, #0
LD R7, SAVER7

RET

GETOP 
ST R7, SAVER7
GETC
OUT

ADD R1,R0,#0
GETC
ADD R0,R1,#0
LD R7, SAVER7

RET

CALC
LD R3, NEGPLUS
ADD R3,R2,R3
BRz addition
LD R3, NEGMINUS
ADD R3, R2, R3
BRz subtraction
BRnzp MULTI

addition
ADD R0,R0, R1
RET

subtraction
NOT R1,R1
ADD R1, R1, #1
ADD R0, R0, R1
RET

MULTI
AND R3,R3,#0
ADD R1,R1,#0
BRz done

MUL
ADD R3,R3,R0
ADD R1,R1,#-1
BRp MUL

done
ADD R0,R3,#0
RET

DISPLAY

ST R7, SAVER7
ADD R1,R0,#0
LEA R0, RESULTM
PUTS

ADD R1, R1,#0
BRzp DIS
LD R0, INIT_X
OUT
NOT R1,R1
ADD R1,R1,#1
DIS
AND R6,R6,#0
LEA R3, PLACES

DLOOP

LDR R4, R3, #0
BRz PEND
AND R2,R2, #0

SUBLOOP
ADD R5, R1,R4
BRn PRINTD
ADD R1, R5, #0
ADD R2, R2, #1

BRnzp SUBLOOP

PRINTD

ADD R2,R2,#0
BRp show

ADD R6,R6,#0
BRp show
ADD R5,R4,#1
BRnp SKIP

show
LD R5, ASSCII0
ADD R0, R2,R5
OUT
ADD R6,R6,#1
SKIP
ADD R3,R3,#1

BRnzp DLOOP

PEND
LD R7, SAVER7

RET

PLACES  .FILL #-1000
        .FILL #-100
        .FILL #-10
        .FILL #-1
        .FILL #0
ASSCII0 .FILL #48
NEGPLUS .FILL #-43
NEGMINUS .FILL #-45
SAVER7  .BLKW 1
NEG48   .FILL #-48
NUM1    .BLKW 1
NUM2    .BLKW 1
OP      .BLKW 1
INIT_X  .FILL X2D

RESULTM .FILL X0A
        .STRINGZ "Result: "
PROMPT1 .FILL X0A
        .STRINGZ "Enter first number(0 - 99): "
PROMPT2 .FILL X0A
        .STRINGZ "Enter an operation(+ , -, *): "
PROMPT3 .FILL X0A
        .STRINGZ "Enter second number(0 - 99): "
.END