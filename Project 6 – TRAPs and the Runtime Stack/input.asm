LD R0, NEWLINE

OUT
ADD R0, R2, #0

LD R1, SAVE_R1
LD R2, SAVE_R2
LD R7, SAVE_R7
RET

NEG_ZERO    .FILL xFFD0
NEWLINE .FILL x000A
SAVE_R1 .BLKW 1
SAVE_R2 .BLKW 1
SAVE_R7 .BLKW 1

.END