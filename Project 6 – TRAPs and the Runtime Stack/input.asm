OUT

LD R1, NEG_ZERO
ADD R0,R0,R1
ADD R1,R0,R0
ADD R2,R1,R1
ADD R2,R2,R2
ADD R1,R1,R2

GETC
OUT
LD R2, NEG_ZERO
ADD R0,R0,R2
ADD R0,R0,R1

