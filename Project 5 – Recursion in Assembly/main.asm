.ORIG x3000

MAIN

LD R6, STACK_TOP

LEA R0, PROMPT
PUTS

GETC
OUT

LD R1, NEG_ASCII
ADD R4, R0, R1
LEA R0, F_START
PUTS

LD R1, ASCII_ZERO
ADD R0, R4, R1
OUT

LEA R0, F_END
PUTS

ADD R0, R4, #0
JSR FIBONACCI

AND R2, R2, #0
LD R1, NEG_TEN


DEVIDE_LOOP

ADD R3, R0, R1
BRn DEVIDE_DONE

ADD R0,R3, #0
ADD R2,R2, #1
BRnzp DEVIDE_LOOP

DEVIDE_DONE
ADD R3,R0,#0

ADD R2,R2, #0
BRz PRINT_ONES

LD R1, ASCII_ZERO
ADD R0, R2, R1
OUT

PRINT_ONES
LD R1, ASCII_ZERO
ADD R0, R3, R1
OUT

LD R0, NEW_LINE
OUT


HALT



FIBONACCI

ADD R6,R6, #-1
STR R7, R6, #0
ADD R6,R6, #-1
STR R5,R6, #0
ADD R6, R6, #-1
STR R0, R6, #0

ADD R6, R6, #-1
ADD R5, R6, #0

LDR R0, R5, #1
BRz BASE_CASE

ADD R1, R0, #-1
BRz BASE_CASE

ADD R0, R0, #-1
JSR FIBONACCI
STR R0, R5, #0

LDR R0, R5, #1
ADD R0, R0, #-2
JSR FIBONACCI

LDR R1, R5, #0
ADD R0, R0, R1
BRnzp FIBONACCI_RETURN


BASE_CASE

LDR R0,R5, #1

FIBONACCI_RETURN

LDR R7, R5, #3
LDR R1, R5, #2
ADD R6, R5, #4
ADD R5, R1, #0

RET

PROMPT  .STRINGZ "Please enter a number: "
F_START    .STRINGZ "\nF("
F_END   .STRINGZ ") = "


ASCII_ZERO  .FILL x0030
NEG_ASCII   .FILL xFFD0
NEG_TEN     .FILL #-10
NEW_LINE    .FILL x000A
STACK_TOP   .FILL xF000


.END